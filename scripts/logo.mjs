// Pulls Premier's vector wordmark from the live site (Webflow CDN, PREMIER_black.svg, Adobe Illustrator export)
// and writes its seven letter shapes to lib/logo.ts, ordered left to right, so the preloader can build them one by one.
// The file draws I as a <polygon> and every other letter as a <path>; polygons are converted to path data here.
// Run: npm run logo
import { writeFileSync } from "node:fs";

const SRC = "https://cdn.prod.website-files.com/5de5569063e17beb5353952b/5e89af81acdbb506b33b9526_PREMIER_black.svg";
const svg = await (await fetch(SRC)).text();
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const shapes = [...svg.matchAll(/<(path|polygon)[^>]*?(?:d|points)="([^"]+)"/g)].map(([, tag, data]) => {
  const d = tag === "path" ? data.replace(/\s+/g, " ").trim()
    : "M" + data.trim().split(/\s+/).join(" L") + " Z";
  const x = Number(d.match(/-?\d+(\.\d+)?/)[0]);
  return { d, x };
}).sort((a, b) => a.x - b.x);
const names = ["P", "R", "E", "M", "I", "E2", "R2"];
if (shapes.length !== names.length) throw new Error(`expected 7 letters, found ${shapes.length}`);
const out = `// Generated by scripts/logo.mjs from ${SRC.split("/").pop()} (live site header logo). Do not edit by hand.
// Seven letter shapes, left to right: P R E M I E R. Colour comes from currentColor.
export const logoViewBox = ${JSON.stringify(viewBox)};
export const logoLetters = [
${shapes.map((s, i) => `  { id: ${JSON.stringify(names[i])}, d: ${JSON.stringify(s.d)} },`).join("\n")}
] as const;
`;
writeFileSync("lib/logo.ts", out);
console.log(`lib/logo.ts: ${shapes.length} letters, viewBox ${viewBox}`);
